export const STRINGS: Record<Locale, Dict> = { en: EN, ru: RU };

export function format(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export type T = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): T {
  return (key, vars) => format(STRINGS[locale][key] ?? STRINGS.en[key] ?? key, vars);
}

/** Plural pick: `{base}.one/.few/.many/.other` by CLDR rules, `{n}` filled in. */
export function plural(locale: Locale, base: string, n: number): string {
  const form = new Intl.PluralRules(locale).select(n);
  const s = STRINGS[locale][`${base}.${form}`] ?? STRINGS[locale][`${base}.other`] ?? STRINGS.en[`${base}.other`] ?? base;
  return format(s, { n });
}
